CREATE TABLE IF NOT EXISTS VIDEO_CONFIG_URL (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guid VARCHAR(255),
    parent_guid VARCHAR(255),
    url VARCHAR(2048)
    );
COMMENT ON TABLE VIDEO_CONFIG_URL IS '剧集平台播放链接的数据库';
COMMENT ON COLUMN VIDEO_CONFIG_URL.id IS '主键ID';
COMMENT ON COLUMN VIDEO_CONFIG_URL.guid IS '剧集ID';
COMMENT ON COLUMN VIDEO_CONFIG_URL.parent_guid IS '母ID(例如季度ID)';
COMMENT ON COLUMN VIDEO_CONFIG_URL.url IS '播放链接';