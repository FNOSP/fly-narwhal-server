-- 2.0.0 final release schema.
--
-- Supersedes the 0.7.0 - 0.13.0 development migrations, which only ever shipped
-- as intermediate builds: this file creates every table in its final shape
-- instead of replaying the add-then-drop history (e.g. the single
-- commercial_start/commercial_end pair on EPISODE_SEGMENTS, replaced by
-- COMMERCIAL_SEGMENTS in 0.8.0; the nullable url and app credentials on
-- DANMU_SOURCE_CONFIG).
--
-- Runs from any earlier version, 0.1.0 upward: 040_init.sql still creates the
-- pre-0.7.0 VIDEO_CONFIG_URL table for those installs, and the danmu source
-- cache is dropped rather than carried over (see the 0.9.0 section below).

