-- 0.8.0: commercials can occur several times per episode, so each one is a row
-- here rather than a start/end pair on EPISODE_SEGMENTS.
CREATE TABLE IF NOT EXISTS COMMERCIAL_SEGMENTS (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_segment_id BIGINT NOT NULL,
    ordinal INT NOT NULL,
    start_time DECIMAL(10, 3) NOT NULL,
    end_time DECIMAL(10, 3) NOT NULL,
    create_time TIMESTAMP,
    update_time TIMESTAMP
);
COMMENT ON TABLE COMMERCIAL_SEGMENTS IS '剧集广告片段表(一部剧集可有多段)';
COMMENT ON COLUMN COMMERCIAL_SEGMENTS.episode_segment_id IS '所属剧集片段记录ID';
COMMENT ON COLUMN COMMERCIAL_SEGMENTS.ordinal IS '片段顺序(从0开始)';
COMMENT ON COLUMN COMMERCIAL_SEGMENTS.start_time IS '广告开始时间(秒)';
COMMENT ON COLUMN COMMERCIAL_SEGMENTS.end_time IS '广告结束时间(秒)';

CREATE INDEX IF NOT EXISTS idx_commercial_segments_episode_segment_id
    ON COMMERCIAL_SEGMENTS (episode_segment_id);

-- 0.11.0 + 0.12.0 + 0.13.0: runtime-editable danmu sources. url is nullable
-- because the dandan_account row carries app_id/app_secret instead; priority
-- stays NULL when no channel preference is set, which reads as "official
-- first, relay second". enabled is the explicit per-row switch (FALSE keeps the
-- configuration but stops the source being used).
CREATE TABLE IF NOT EXISTS DANMU_SOURCE_CONFIG (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type VARCHAR(32) NOT NULL,
    name VARCHAR(128),
    url VARCHAR(512),
    enabled BOOLEAN DEFAULT TRUE,
    app_id VARCHAR(64),
    app_secret VARCHAR(128),
    priority INT,
    create_time TIMESTAMP,
    update_time TIMESTAMP
);
COMMENT ON TABLE DANMU_SOURCE_CONFIG IS '弹幕源配置表(弹弹play中转与第三方兜底弹幕服务器,可在客户端设置页运行时修改)';
COMMENT ON COLUMN DANMU_SOURCE_CONFIG.id IS '主键ID';
COMMENT ON COLUMN DANMU_SOURCE_CONFIG.source_type IS '配置类型: dandan_relay=弹弹play中转(单行), fallback_server=第三方兜底弹幕服务器(可多行)';
COMMENT ON COLUMN DANMU_SOURCE_CONFIG.name IS '显示名称(兜底服务器用,弹弹行为空)';
COMMENT ON COLUMN DANMU_SOURCE_CONFIG.url IS '服务器基地址(弹弹为ddp中转地址,兜底为 ?url=&ac=dm 契约服务器)';
COMMENT ON COLUMN DANMU_SOURCE_CONFIG.enabled IS '是否启用(FALSE=停用但保留配置)';
COMMENT ON COLUMN DANMU_SOURCE_CONFIG.app_id IS '弹弹play开放平台AppId(source_type=dandan_account行)';
COMMENT ON COLUMN DANMU_SOURCE_CONFIG.app_secret IS '弹弹play开放平台AppSecret(source_type=dandan_account行)';
COMMENT ON COLUMN DANMU_SOURCE_CONFIG.priority IS '弹弹play取源优先级(0=首选,1=次选);NULL=未设置,按官方优先推导';
COMMENT ON COLUMN DANMU_SOURCE_CONFIG.create_time IS '创建时间';
COMMENT ON COLUMN DANMU_SOURCE_CONFIG.update_time IS '更新时间';

-- 0.9.0: the danmu source cache table is renamed from VIDEO_CONFIG_URL to
-- DANMU_PLATFORM_URL, because it never held general playback links, only the
-- platform page used to fetch an episode's danmaku. 0.4.0 still creates the old
-- name for databases below 0.7.0; those rows are not carried over, the cache is
-- rebuilt on demand.
CREATE TABLE IF NOT EXISTS DANMU_PLATFORM_URL (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guid VARCHAR(255),
    parent_guid VARCHAR(255),
    url VARCHAR(2048)
    );
COMMENT ON TABLE DANMU_PLATFORM_URL IS '剧集弹幕源链接缓存表(记录某集在视频平台的播放页地址,供弹幕抓取使用)';
COMMENT ON COLUMN DANMU_PLATFORM_URL.id IS '主键ID';
COMMENT ON COLUMN DANMU_PLATFORM_URL.guid IS '剧集ID';
COMMENT ON COLUMN DANMU_PLATFORM_URL.parent_guid IS '母ID(例如季度ID)';
COMMENT ON COLUMN DANMU_PLATFORM_URL.url IS '弹幕源页面链接';

DROP TABLE IF EXISTS VIDEO_CONFIG_URL;

