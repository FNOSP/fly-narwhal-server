CREATE TABLE IF NOT EXISTS DB_VERSION (
    id INT PRIMARY KEY,
    version VARCHAR(64) NOT NULL,
    update_time TIMESTAMP
);
COMMENT ON TABLE DB_VERSION IS '数据库版本表';
COMMENT ON COLUMN DB_VERSION.id IS '主键ID';
COMMENT ON COLUMN DB_VERSION.version IS '版本号';
COMMENT ON COLUMN DB_VERSION.update_time IS '更新时间';

CREATE TABLE IF NOT EXISTS SERIES_EPISODES (
    series_guid VARCHAR(255) NOT NULL PRIMARY KEY,
    season_folder_path VARCHAR(2048),
    tv_title VARCHAR(255),
    season_number INT,
    status VARCHAR(32)
);
COMMENT ON TABLE SERIES_EPISODES IS '剧集季度信息表';
COMMENT ON COLUMN SERIES_EPISODES.series_guid IS '剧集GUID';
COMMENT ON COLUMN SERIES_EPISODES.season_folder_path IS '季度文件夹路径';
COMMENT ON COLUMN SERIES_EPISODES.tv_title IS '剧集标题';
COMMENT ON COLUMN SERIES_EPISODES.season_number IS '季度编号';
COMMENT ON COLUMN SERIES_EPISODES.status IS '分析状态';

CREATE TABLE IF NOT EXISTS EPISODE_SEGMENTS (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guid VARCHAR(255),
    series_guid VARCHAR(255),
    file_path VARCHAR(2048),
    episode_number INT,
    duration DOUBLE,
    intro_start INT,
    intro_end INT,
    credits_start INT,
    credits_end INT,
    intro_fingerprint BLOB,
    credits_fingerprint BLOB,
    action VARCHAR(255),
    create_time TIMESTAMP,
    update_time TIMESTAMP
);
COMMENT ON TABLE EPISODE_SEGMENTS IS '剧集片段信息表';
COMMENT ON COLUMN EPISODE_SEGMENTS.id IS '主键ID';
COMMENT ON COLUMN EPISODE_SEGMENTS.guid IS '唯一标识';
COMMENT ON COLUMN EPISODE_SEGMENTS.series_guid IS '剧集GUID';
COMMENT ON COLUMN EPISODE_SEGMENTS.file_path IS '文件路径';
COMMENT ON COLUMN EPISODE_SEGMENTS.episode_number IS '剧集索引';
COMMENT ON COLUMN EPISODE_SEGMENTS.duration IS '时长';
COMMENT ON COLUMN EPISODE_SEGMENTS.intro_start IS '片头开始时间';
COMMENT ON COLUMN EPISODE_SEGMENTS.intro_end IS '片头结束时间';
COMMENT ON COLUMN EPISODE_SEGMENTS.credits_start IS '片尾开始时间';
COMMENT ON COLUMN EPISODE_SEGMENTS.credits_end IS '片尾结束时间';
COMMENT ON COLUMN EPISODE_SEGMENTS.intro_fingerprint IS '片头指纹';
COMMENT ON COLUMN EPISODE_SEGMENTS.credits_fingerprint IS '片尾指纹';
COMMENT ON COLUMN EPISODE_SEGMENTS.action IS '使用的分析器';
COMMENT ON COLUMN EPISODE_SEGMENTS.create_time IS '创建时间';
COMMENT ON COLUMN EPISODE_SEGMENTS.update_time IS '更新时间';